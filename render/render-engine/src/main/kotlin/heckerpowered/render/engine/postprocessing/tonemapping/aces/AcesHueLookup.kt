package heckerpowered.render.engine.postprocessing.tonemapping.aces

/**
 * Immutable lookup data shared by chroma and gamut compression. Cusp samples follow the nonuniform
 * hue grid; reach samples follow uniform one-degree steps. Their indices are not interchangeable.
 * Each grid includes three wrapping entries. Search bounds accelerate the nonuniform-grid lookup.
 *
 * All arrays, including every cusp row, are copied after generation finishes. Copies of enclosing
 * data values can safely share this snapshot without changing equality or hash codes.
 */
internal class AcesHueLookup(hues: FloatArray, cusp: Array<FloatArray>, reach: FloatArray, hueSearchRange: IntArray) {
    private val hues = hues.copyOf()
    private val cusp = Array(cusp.size) { cusp[it].copyOf() }
    private val reach = reach.copyOf()
    private val hueSearchRange = hueSearchRange.copyOf()

    val size: Int get() = hues.size
    val searchLow: Int get() = hueSearchRange[0]
    val searchHigh: Int get() = hueSearchRange[1]

    fun hue(index: Int): Float = hues[index]

    /**
     * Returns one coefficient of the limiting-display cusp at the nonuniform angle [hue].
     * This is direct table access: [index] selects a row, not a hue in degrees, and no
     * interpolation or index wrapping is performed here.
     *
     * Component 0 is cusp lightness J, with reference-white J=100 at 100 cd/m².
     * Component 1 is cusp colorfulness M multiplied by `1 + 0.27 * 0.12` to compensate
     * for the smooth hull join. J and M are appearance-model coordinates, not nits or
     * normalized RGB values; neither is restricted to 0..1. Component 2 is the
     * dimensionless reciprocal upper-hull exponent produced by `fitUpperHull`, not hue.
     *
     * Tables generated by [gamutCompression] contain 363 rows. Rows 1..360 are the
     * interior samples; rows 0, 361 and 362 copy rows 360, 1 and 2 for seam interpolation.
     * Their angles come from [hue], not from `index - 1` as in [reach].
     *
     * @param index Row in `0 until size` for the generated lookup, including seam neighbors.
     * @param component Coefficient selector: 0 for J, 1 for expanded M, or 2 for inverse gamma.
     * @throws IndexOutOfBoundsException If either index lies outside the stored arrays.
     */
    fun cusp(index: Int, component: Int): Float = cusp[index][component]

    /**
     * Returns AP1 reach colorfulness M at the configured display-peak lightness J.
     * [reachTable] holds J fixed and searches along M until an AP1 RGB channel becomes
     * negative. The stored value is the upper side of that numerical search bracket;
     * it describes the reach boundary, not the limiting-display cusp returned by [cusp].
     *
     * M uses the appearance model's opponent-coordinate scale, not nits, degrees or
     * a 0..1 RGB fraction. Display peak is converted from cd/m² to J before generation.
     * These samples are uniformly spaced: rows 1..360 represent hues 0..359 degrees.
     * Rows 0, 361 and 362 copy rows 360, 1 and 2 respectively, extending the periodic
     * grid to -1, 360 and 361 degrees for interpolation across the seam.
     *
     * This accessor does not interpolate or wrap [index]. Although [cusp] and reach
     * share texture rows, the same row generally represents different hue angles:
     * cusp uses the nonuniform [hue] grid, while reach uses `index - 1` degrees.
     *
     * @param index Row in `0 until size` for the generated 363-entry lookup.
     * @throws IndexOutOfBoundsException If [index] lies outside the stored reach array.
     */
    fun reach(index: Int): Float = reach[index]

    override fun equals(other: Any?): Boolean = this === other || other is AcesHueLookup && hues.contentEquals(other.hues) && cusp.contentDeepEquals(other.cusp) && reach.contentEquals(other.reach) && hueSearchRange.contentEquals(other.hueSearchRange)

    override fun hashCode(): Int {
        var result = hues.contentHashCode()
        result = 31 * result + cusp.contentDeepHashCode()
        result = 31 * result + reach.contentHashCode()
        return 31 * result + hueSearchRange.contentHashCode()
    }
}
